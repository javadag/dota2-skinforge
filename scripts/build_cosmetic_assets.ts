/**
 * Generate `data/cosmetic-assets.json` from an extracted pack bundle.
 *
 * For every hero group the bundle patched, the patched block keeps the cosmetic's
 * `item_name`; matching that back to a non-default item in the same schema identifies
 * which arcana/persona the group's files belong to.
 *
 *   npx tsx scripts/build_cosmetic_assets.ts --bundle D:\changer_changed
 */

import fs from 'fs'
import path from 'path'

import * as packService from '../src/main/services/packService'

function arg(name: string, fallback?: string): string | undefined {
  const i = process.argv.indexOf(name)
  if (i !== -1 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--')) return process.argv[i + 1]
  return fallback
}

const META = new Set(['manifest.json', 'items_patch.txt', 'items_patch_all.txt'])

interface Meta {
  id: string
  name: string
  itemName?: string
  prefab: string
  rarity?: string
  slot?: string
}

function readField(block: string, key: string): string | undefined {
  const m = new RegExp(`"${key}"\\s+"([^"]*)"`).exec(block)
  return m?.[1]
}

function walk(dir: string, prefix = ''): string[] {
  const out: string[] = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), rel))
    else out.push(rel)
  }
  return out
}

function main(): void {
  const bundle = path.resolve(arg('--bundle', 'D:\\changer_changed')!)
  const outFile = path.resolve(arg('--out', 'data/cosmetic-assets.json')!)

  const schemaPath = path.join(bundle, '_global', 'scripts', 'items', 'items_game.txt')
  if (!fs.existsSync(schemaPath)) {
    throw new Error(
      `Bundle has no _global/scripts/items/items_game.txt (${schemaPath}). ` +
        'The generator needs the patched schema to identify which cosmetic each group carries.'
    )
  }

  console.log(`schema  ${schemaPath}`)
  const text = fs.readFileSync(schemaPath, 'utf-8')
  const section = packService.readItemsSection(text)
  console.log(`items   ${section.blocks.size}`)

  const byItemName = new Map<string, Meta[]>()

  for (const [id, span] of section.blocks) {
    const block = text.slice(span.start, span.end)
    const meta: Meta = {
      id,
      name: readField(block, 'name') ?? id,
      itemName: readField(block, 'item_name'),
      prefab: readField(block, 'prefab') ?? '',
      rarity: readField(block, 'item_rarity'),
      slot: readField(block, 'item_slot')
    }
    if (meta.itemName) {
      const list = byItemName.get(meta.itemName) ?? []
      list.push(meta)
      byItemName.set(meta.itemName, list)
    }
  }

  const isCosmetic = (m: Meta): boolean =>
    m.prefab !== 'default_item' &&
    m.prefab !== 'bundle' &&
    (m.rarity === 'arcana' || m.slot === 'persona_selector' || /persona/i.test(m.name))

  const score = (m: Meta): number => {
    let s = 0
    if (m.rarity === 'arcana') s += 10
    if (m.slot === 'persona_selector') s += 10
    if (/persona/i.test(m.name)) s += 5
    if (m.slot === 'hero_base') s += 3
    if (m.slot) s += 1
    return s
  }

  const items: Record<string, { name: string; hero: string; group: string; patch?: string; files: string[] }> = {}
  const skipped: string[] = []

  for (const entry of fs.readdirSync(bundle, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === '_branding') continue
    const dir = path.join(bundle, entry.name)
    const patchPath = path.join(dir, 'items_patch.txt')
    if (!fs.existsSync(patchPath)) continue

    const files = walk(dir).filter((rel) => !META.has(path.posix.basename(rel)))
    if (!files.length) continue

    const patchText = fs.readFileSync(patchPath, 'utf-8')
    const targets = [...packService.readPatchBlocks(patchText).keys()]

    const candidates = new Map<string, Meta>()
    for (const target of targets) {
      const span = section.blocks.get(target)
      if (!span) continue
      const itemName = readField(text.slice(span.start, span.end), 'item_name')
      if (!itemName) continue
      for (const candidate of byItemName.get(itemName) ?? []) {
        if (candidate.id === target || !isCosmetic(candidate)) continue
        candidates.set(candidate.id, candidate)
      }
    }

    if (!candidates.size) {
      skipped.push(entry.name)
      continue
    }

    const best = [...candidates.values()].sort((a, b) => score(b) - score(a) || a.name.length - b.name.length)[0]

    items[best.id] = {
      name: best.name,
      hero: entry.name,
      group: entry.name,
      patch: 'items_patch.txt',
      files
    }
  }

  const manifest = {
    $comment:
      'Cosmetics that need real file swaps. Generated by scripts/build_cosmetic_assets.ts from an extracted pack: <sourceDir>/<group>/<file> mirrors the game-relative path.',
    sourceDir: bundle,
    items
  }

  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, JSON.stringify(manifest, null, 2) + '\n', 'utf-8')

  const total = Object.values(items).reduce((sum, e) => sum + e.files.length, 0)
  console.log(`wrote   ${outFile}`)
  console.log(`entries ${Object.keys(items).length}  files ${total}`)
  if (skipped.length) console.log(`skipped ${skipped.length} groups without an arcana/persona: ${skipped.join(', ')}`)
  for (const [id, e] of Object.entries(items).sort((a, b) => a[1].hero.localeCompare(b[1].hero))) {
    console.log(`  ${id.padStart(6)}  ${e.hero.padEnd(20)} ${e.files.length.toString().padStart(4)} files  ${e.name}`)
  }
}

main()
